#!/usr/bin/env node
/* ds-sync — write the production token stylesheets from the design-system
   export (docs/design/tokens.json). ds-check verifies the result. */

import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { loadTokens } from './lib/ds-tokens.js';

const ROOT = resolve(import.meta.dirname, '..');
const TOKENS = join(ROOT, 'docs/design/tokens.json');
const CSS_DIR = join(ROOT, 'assets/css');
const DARK_PREFIX = '--_dk-';

const declarations = (map, indent = '  ') =>
  [...map].map(([name, value]) => `${indent}${name}: ${value};`).join('\n');

const header = (what) =>
  `/* quarksCharm — ${what}. Generated by scripts/ds-sync.js from\n   docs/design/tokens.json; edit the design system, not this file. */\n\n`;

const typography = (tokens) => {
  const lines = [];
  for (const group of tokens.type.groups) {
    for (const style of group.styles) {
      const family = style.family ?? group.family;
      const props = [
        `font-family: var(--font-${family});`,
        `font-size: ${style.fontSize};`,
        `line-height: ${style.lineHeight};`,
        `font-weight: ${style.fontWeight};`,
      ];
      if (style.letterSpacing)
        props.push(`letter-spacing: ${style.letterSpacing};`);
      lines.push(`.${style.name} {\n  ${props.join('\n  ')}\n}`);
    }
  }
  return lines.join('\n\n') + '\n';
};

const main = () => {
  const tokens = JSON.parse(readFileSync(TOKENS, 'utf8'));
  const { light, dark, shared } = loadTokens(tokens);

  const darkPrivate = new Map(
    [...dark].map(([name, value]) => [DARK_PREFIX + name.slice(2), value]),
  );
  const darkPublic = new Map(
    [...dark.keys()].map((name) => [
      name,
      `var(${DARK_PREFIX}${name.slice(2)})`,
    ]),
  );

  const files = {
    'tokens.css':
      header('spacing, radii, fonts') + `:root {\n${declarations(shared)}\n}\n`,
    'theme-light.css':
      header('light theme colours and shadows') +
      `:root {\n${declarations(light)}\n}\n`,
    'theme-dark.css':
      header('dark theme colours and shadows') +
      `:root {\n${declarations(darkPrivate)}\n}\n\n` +
      `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme='light']) {\n    color-scheme: dark;\n${declarations(darkPublic, '    ')}\n  }\n}\n\n` +
      `:root[data-theme='dark'] {\n  color-scheme: dark;\n${declarations(darkPublic)}\n}\n`,
    'typography.css': header('type styles') + typography(tokens),
  };
  for (const [name, content] of Object.entries(files)) {
    writeFileSync(join(CSS_DIR, name), content);
    console.log(`ds-sync: wrote assets/css/${name}`);
  }
};

main();
